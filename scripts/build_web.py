#!/usr/bin/env python3
"""Build the static client using the existing Python tables (no dependencies)."""

import argparse
import json
from pathlib import Path
import shutil
import sys
from urllib.parse import urlsplit
import re

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import calculator
from airports import AIRPORTS
from programs import ALLIANCES, PROGRAM_LIST, PROGRAMS, _CLASS_BAND
from ui_options import AIRLINE_OPTIONS, BOOKING_CLASS_OPTIONS


def build(output: Path, gateway_url: str = "") -> None:
    gateway_url = gateway_url.rstrip("/")
    origin = ""
    if gateway_url:
        parts = urlsplit(gateway_url)
        if not re.fullmatch(r"https?://[A-Za-z0-9.-]+(?::\d{1,5})?", gateway_url) or (parts.scheme != "https" and parts.hostname not in {"localhost", "127.0.0.1"}):
            raise ValueError("Use an HTTPS gateway origin, or a loopback HTTP origin for development.")
        origin = gateway_url
    output.mkdir(parents=True, exist_ok=True)
    for source in (ROOT / "web").iterdir():
        if source.is_file():
            shutil.copyfile(source, output / source.name)
    (output / "config.js").write_text(f"export const gatewayUrl = {json.dumps(gateway_url)};\n", encoding="utf-8")
    if origin:
        html_path = output / "index.html"
        html_path.write_text(html_path.read_text(encoding="utf-8").replace("connect-src 'self';", f"connect-src 'self' {origin};"), encoding="utf-8")

    data = {
        "airports": AIRPORTS,
        "airlines": AIRLINE_OPTIONS,
        "booking_classes": BOOKING_CLASS_OPTIONS,
        "program_list": PROGRAM_LIST,
        "programs": PROGRAMS,
        "alliances": ALLIANCES,
        "class_bands": _CLASS_BAND,
        "cathay_short_type2_airports": sorted(calculator._CATHAY_SHORT_TYPE2_AIRPORTS),
        "cathay_status_by_class": calculator._CATHAY_STATUS_POINTS_BY_CLASS,
        "velocity_status_bands": calculator._VELOCITY_STATUS_BANDS,
        "velocity_business_classes": sorted(calculator._VELOCITY_BUSINESS_CLASSES),
        "velocity_flex_classes": sorted(calculator._VELOCITY_FLEX_CLASSES),
        "velocity_choice_classes": sorted(calculator._VELOCITY_CHOICE_CLASSES),
    }
    content = json.dumps(data, ensure_ascii=False, separators=(",", ":"), allow_nan=False)
    (output / "data.js").write_text(
        "// Generated by scripts/build_web.py; edit the Python tables instead.\n"
        f"export default {content};\n", encoding="utf-8"
    )
    (output / ".nojekyll").touch()
    print(f"Static site built at {output}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "dist")
    parser.add_argument("--gateway-url", default="", help="Public HTTPS origin of the search gateway; default: same origin as the website")
    args = parser.parse_args()
    build(args.output.resolve(), args.gateway_url)
